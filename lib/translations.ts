export function translate(language: Language, source: string, values?: TranslationValues) {
  const key = source.trim().replace(/\.$/, '');
  const text = language === 'ka' && Object.prototype.hasOwnProperty.call(georgian, key) ? georgian[key] : key;
  return values ? text.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match)) : text;
}

export function translateMessage(language: Language, message: string): string {
  if (language === 'en') return translate(language, message);
  const minLength = /^Use at least (\d+) characters for the password\.?$/.exec(message);
  if (minLength) return translate(language, 'Use at least {count} characters for the password', { count: minLength[1] });
  const range = /^Use (\d+) to 128 characters for the new password\.?$/.exec(message);
  if (range) return translate(language, 'Use {min} to 128 characters for the new password', { min: range[1] });
  const visibility = /^Page visibility: (\w+)\.?$/.exec(message);
  if (visibility) return translate(language, 'Page visibility: {state}', { state: translate(language, visibility[1]) });
  const audioState = /^AudioContext state is (\w+)\.?$/.exec(message);
  if (audioState) return translate(language, 'AudioContext state is {state}', { state: translate(language, audioState[1]) });
  const apiDetail = /^(GPS|DeviceMotion|AudioContext|AudioWorklet): (.+)$/.exec(message);
  if (apiDetail) {
    const [summary, ...details] = apiDetail[2].split(' · ');
    return `${apiDetail[1]} · ${[translateMessage(language, summary), ...details].join(' · ')}`;
  }
  return translate(language, message);
}
